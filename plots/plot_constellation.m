function fig = plot_constellation(symbols, title_str, ref_const, fig_tag)
% Plot complex symbols in the I/Q plane.

    fig = figure('Name', fig_tag, 'NumberTitle', 'off', 'Color', 'w', ...
                 'Position', [100, 100, 650, 600]);
    ax = gca;
    hold(ax, 'on');

    set(ax, 'Color', [1 1 1], ...
            'XColor', [0.15 0.15 0.15], ...
            'YColor', [0.15 0.15 0.15], ...
            'LineWidth', 1.1, ...
            'FontSize', 10, ...
            'FontName', 'Helvetica');

    thresholds = (-6:2:6) / sqrt(42);
    lim_val    = 8 / sqrt(42);

    for th = thresholds
        plot(ax, [th, th], [-lim_val, lim_val], ':', 'Color', [0.82 0.85 0.88], ...
             'LineWidth', 0.9, 'HandleVisibility', 'off');
        plot(ax, [-lim_val, lim_val], [th, th], ':', 'Color', [0.82 0.85 0.88], ...
             'LineWidth', 0.9, 'HandleVisibility', 'off');
    end

    N_pts = length(symbols);
    if N_pts <= 64
        scatter(ax, real(symbols), imag(symbols), 55, ...
            'MarkerFaceColor', [0.00 0.45 0.85], ...
            'MarkerEdgeColor', [0.00 0.20 0.50], ...
            'LineWidth', 1.2, ...
            'DisplayName', 'Ideal Constellation');
    else
        if N_pts > 10000
            idx_sub = round(linspace(1, N_pts, 10000));
            sym_plot = symbols(idx_sub);
        else
            sym_plot = symbols;
        end
        scatter(ax, real(sym_plot), imag(sym_plot), 12, ...
            'MarkerFaceColor', [0.10 0.40 0.80], ...
            'MarkerEdgeColor', 'none', ...
            'MarkerFaceAlpha', 0.35, ...
            'DisplayName', 'Received Symbols');
    end

    if nargin >= 3 && ~isempty(ref_const) && N_pts > 64
        scatter(ax, real(ref_const), imag(ref_const), 45, ...
            'MarkerFaceColor', 'none', ...
            'MarkerEdgeColor', [0.85 0.15 0.15], ...
            'LineWidth', 1.5, ...
            'Marker', 'square', ...
            'DisplayName', 'Reference Grid');
        legend(ax, 'Location', 'northeast', 'FontSize', 9, 'Box', 'on', ...
               'Color', [1 1 1], 'EdgeColor', [0.8 0.8 0.8], 'TextColor', [0.1 0.1 0.1]);
    end

    xlabel(ax, 'In-Phase (I)', 'FontSize', 11, 'FontWeight', 'bold', 'Color', [0.1 0.1 0.1]);
    ylabel(ax, 'Quadrature (Q)', 'FontSize', 11, 'FontWeight', 'bold', 'Color', [0.1 0.1 0.1]);
    title(ax, title_str, 'FontSize', 11, 'FontWeight', 'bold', 'Color', [0.05 0.05 0.05]);

    box(ax, 'on');
    grid(ax, 'on');
    set(ax, 'GridColor', [0.75 0.75 0.75], 'GridAlpha', 0.4);
    axis(ax, 'equal');

    margin = 0.15;
    xlim(ax, [-lim_val - margin, lim_val + margin]);
    ylim(ax, [-lim_val - margin, lim_val + margin]);

    set(ax, 'XTick', [-1.0, -0.5, 0, 0.5, 1.0], ...
            'YTick', [-1.0, -0.5, 0, 0.5, 1.0]);
end
